#!/bin/bash
# Rebuild css/site.css from the two editable sources.
#   css/styles.css     incumbent base layer
#   css/elevation.css  v3+ layer (all current design work)
# Unused rules are purged against the pages, then duplicates and overridden
# declarations are merged. Runtime classes added by JS live in tools/css-safelist.html.
set -euo pipefail
cd "$(dirname "$0")/.."
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cat css/styles.css css/elevation.css > "$TMP/combined.css"
npx -y purgecss@6.0.0 --css "$TMP/combined.css" \
  --content index.html about.html projects.html 404.html js/elevation.js js/gold-particles.js tools/css-safelist.html \
  --output "$TMP/"
{ echo "/* site.css: generated by tools/build-css.sh from css/styles.css + css/elevation.css. Edit the sources, not this file. */"
  npx -y csso-cli@4.0.2 -i "$TMP/combined.css"; } > css/site.css
echo "css/site.css: $(wc -c < css/site.css) bytes"
